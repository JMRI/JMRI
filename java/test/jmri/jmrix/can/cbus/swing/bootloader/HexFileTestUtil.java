package jmri.jmrix.can.cbus.swing.bootloader;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.List;

import static jmri.jmrix.can.cbus.node.CbusNodeConstants.*;

/**
 * Helpers to build small Intel hex files for bootloader tests.
 */
final class HexFileTestUtil {

    private HexFileTestUtil() {
    }

    /**
     * Build one Intel hex record, with a correct record checksum.
     *
     * @param addr 16-bit record address
     * @param type record type
     * @param data data bytes, may be empty
     * @return the record text, without line terminator
     */
    static String record(int addr, int type, int... data) {
        StringBuilder sb = new StringBuilder(":");
        int sum = data.length + ((addr >> 8) & 0xFF) + (addr & 0xFF) + type;
        sb.append(String.format("%02X%04X%02X", data.length, addr & 0xFFFF, type));
        for (int d : data) {
            sb.append(String.format("%02X", d & 0xFF));
            sum += d & 0xFF;
        }
        sb.append(String.format("%02X", (-sum) & 0xFF));
        return sb.toString();
    }

    /**
     * Build a data record.
     *
     * @param addr 16-bit record address
     * @param data data bytes
     * @return the record text
     */
    static String data(int addr, int... data) {
        return record(addr, HexRecord.TYPE_DATA, data);
    }

    /**
     * Build an end of file record.
     *
     * @return the record text
     */
    static String eof() {
        return record(0, HexRecord.END);
    }

    /**
     * Build an extended linear address record.
     *
     * @param upper upper 16 bits of the address
     * @return the record text
     */
    static String extAddr(int upper) {
        return record(0, HexRecord.EXT_ADDR, (upper >> 8) & 0xFF, upper & 0xFF);
    }

    /**
     * Write records to a new hex file in the given directory.
     *
     * @param dir directory to write to
     * @param fileName file name
     * @param records the records
     * @return the file
     * @throws IOException on write failure
     */
    static File write(File dir, String fileName, String... records) throws IOException {
        File f = new File(dir, fileName);
        Files.write(f.toPath(), (String.join("\n", records) + "\n").getBytes(StandardCharsets.US_ASCII));
        return f;
    }

    /**
     * Build a valid 32-byte "new" style CBUS parameter block as found at
     * 0x820 in a PIC hex file.
     * <p>
     * The last two bytes hold the little endian 16-bit sum of the first 30
     * bytes, as generated by the MERG PIC firmware.
     *
     * @param manuId manufacturer ID
     * @param moduleId module ID
     * @param loadAddress load address
     * @return 32 bytes of parameters, element 0 is parameter 1
     */
    static int[] newParamBlock(int manuId, int moduleId, int loadAddress) {
        int[] p = new int[CbusPicHexFile.PARAM_NEW_LEN];
        p[MANU_ID_IDX - 1] = manuId;
        p[MINOR_VER_IDX - 1] = 'a';
        p[MODULE_ID_IDX - 1] = moduleId;
        p[NUM_EV_IDX - 1] = 32;
        p[EV_PER_EN_IDX - 1] = 2;
        p[NUM_NV_IDX - 1] = 16;
        p[MAJOR_VER_IDX - 1] = 2;
        p[FLAGS_IDX - 1] = 0x0D;
        p[PROC_TYPE_IDX - 1] = 13;
        p[BUS_TYPE_IDX - 1] = 1;
        p[LOAD_ADDR_IDX - 1] = loadAddress & 0xFF;
        p[LOAD_ADDR_IDX] = (loadAddress >> 8) & 0xFF;
        p[LOAD_ADDR_IDX + 1] = (loadAddress >> 16) & 0xFF;
        p[LOAD_ADDR_IDX + 2] = (loadAddress >> 24) & 0xFF;
        p[CPU_CODE_IDX - 1] = 1;
        p[BETA_REV_IDX - 1] = 0;
        p[PARAM_COUNT_IDX - 1] = 20;
        p[PARAM_COUNT_IDX] = 0;
        p[NAME_STRING_BASE_IDX - 1] = 0x40;
        p[NAME_STRING_BASE_IDX] = 0x08;
        setChecksum(p);
        return p;
    }

    /**
     * Set the checksum bytes of a parameter block to the 16-bit sum of
     * parameters 1 - 30.
     *
     * @param p 32 byte parameter block, element 0 is parameter 1
     */
    static void setChecksum(int[] p) {
        int sum = 0;
        for (int i = 0; i < PARAM_CHECK_IDX - 1; i++) {
            sum += p[i] & 0xFF;
        }
        p[PARAM_CHECK_IDX - 1] = sum & 0xFF;
        p[PARAM_CHECK_IDX] = (sum >> 8) & 0xFF;
    }

    /**
     * Split a block of bytes into data records of a given length.
     *
     * @param addr start address
     * @param block the bytes
     * @param recLen bytes per record
     * @return the records
     */
    static List<String> dataRecords(int addr, int[] block, int recLen) {
        List<String> recs = new ArrayList<>();
        for (int i = 0; i < block.length; i += recLen) {
            int n = Math.min(recLen, block.length - i);
            int[] d = new int[n];
            System.arraycopy(block, i, d, 0, n);
            recs.add(data(addr + i, d));
        }
        return recs;
    }

    /**
     * Get a block of bytes with a repeated fill value.
     *
     * @param len number of bytes
     * @param fill the fill value
     * @return the bytes
     */
    static int[] fill(int len, int fill) {
        int[] d = new int[len];
        java.util.Arrays.fill(d, fill);
        return d;
    }

}
